# --------------------------------------------------------------------------
# Configuration
# --------------------------------------------------------------------------
def _get_int(configuration, key, default, minimum=0):
    raw = configuration.get(key)
    if raw is None or str(raw).strip() == "":
        return default
    try:
        value = int(str(raw).strip())
    except ValueError:
        raise ValueError(f"Configuration '{key}' must be a whole number, got '{raw}'")
    if value < minimum:
        raise ValueError(f"Configuration '{key}' must be >= {minimum}, got {value}")
    return value


def parse_config(configuration):
    cfg = {
        "reference_count": _get_int(configuration, f"{REF['table']}_count", 100, minimum=1),
        "seed": str(configuration.get("seed", "42")),
        "incremental_min": _get_int(configuration, "incremental_min", 5),
        "incremental_max": _get_int(configuration, "incremental_max", 25),
        "history": {},
    }
    if cfg["incremental_min"] > cfg["incremental_max"]:
        raise ValueError("incremental_min cannot be greater than incremental_max")
    for child in CHILDREN:
        t = child["table"]
        lo = _get_int(configuration, f"{t}_min", 1)
        hi = _get_int(configuration, f"{t}_max", max(lo, 5))
        if lo > hi:
            raise ValueError(f"Configuration '{t}_min' ({lo}) cannot be greater than '{t}_max' ({hi})")
        cfg["history"][t] = (lo, hi)
    return cfg


# --------------------------------------------------------------------------
# Row generation
# --------------------------------------------------------------------------
def _gen_value(spec, rng, ctx, row):
    kind = spec["kind"]
    if kind == "choice":
        return rng.choices(spec["values"], weights=spec.get("weights"))[0]
    if kind == "int":
        return rng.randint(spec["min"], spec["max"])
    if kind == "decimal":
        return round(rng.uniform(spec["min"], spec["max"]), spec.get("places", 2))
    if kind == "bool":
        return rng.random() < spec.get("p", 0.5)
    if kind == "first_name":
        return rng.choice(FIRST_NAMES)
    if kind == "last_name":
        return rng.choice(LAST_NAMES)
    if kind == "company":
        return f"{rng.choice(COMPANY_A)} {rng.choice(COMPANY_B)}"
    if kind == "email":
        first = str(row.get("first_name", "user")).lower()
        last = str(row.get("last_name", "demo")).lower()
        return f"{first}.{last}{ctx['pk']}@example.com"
    if kind == "past_time":
        return ctx["epoch"] - timedelta(days=rng.uniform(1, spec["max_days_back"]))
    if kind == "event_time":
        if ctx["mode"] == "history":
            start = ctx["anchor"]
            span = max((ctx["epoch"] - start).total_seconds(), 1.0)
            return start + timedelta(seconds=rng.uniform(0, span))
        return ctx["now"] - timedelta(seconds=rng.uniform(0, 300))
    raise ValueError(f"Unknown generator kind '{kind}'")


def _build_row(table_def, pk_value, rng, ctx, fk_value=None):
    row = {table_def["pk"]: pk_value}
    if fk_value is not None:
        row[REF["pk"]] = fk_value
    ctx = dict(ctx, pk=pk_value)
    for name, col in table_def["columns"].items():
        row[name] = _gen_value(col["gen"], rng, ctx, row)
    return row


def _serialise(row):
    out = {}
    for key, value in row.items():
        if isinstance(value, datetime):
            out[key] = value.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.%f")[:-3] + "Z"
        else:
            out[key] = value
    return out


def _utc_now():
    return datetime.now(timezone.utc)


def _parse_iso(value):
    return datetime.strptime(value, "%Y-%m-%dT%H:%M:%S.%fZ").replace(tzinfo=timezone.utc)


# --------------------------------------------------------------------------
# Schema
# --------------------------------------------------------------------------
def schema(configuration):
    tables = []

    ref_cols = {REF["pk"]: "LONG"}
    ref_cols.update({n: c["type"] for n, c in REF["columns"].items()})
    tables.append({"table": REF["table"], "primary_key": [REF["pk"]], "columns": ref_cols})

    for child in CHILDREN:
        cols = {child["pk"]: "LONG", REF["pk"]: "LONG"}
        cols.update({n: c["type"] for n, c in child["columns"].items()})
        tables.append({"table": child["table"], "primary_key": [child["pk"]], "columns": cols})

    return tables


# --------------------------------------------------------------------------
# Sync logic
# --------------------------------------------------------------------------
def _fresh_state(cfg):
    return {
        "history_complete": False,
        "history_cursor": 0,
        "reference_total": cfg["reference_count"],
        "epoch": _utc_now().strftime("%Y-%m-%dT%H:%M:%S.%f")[:-3] + "Z",
        "next_ids": {c["table"]: 1 for c in CHILDREN},
        "sync_count": 0,
        "last_tables_updated": [],
    }


def historical_load(cfg, state):
    epoch = _parse_iso(state["epoch"])
    total = state["reference_total"]
    start_at = state["history_cursor"] + 1
    log.info(f"History load: {REF['table']} rows {start_at}..{total}, "
             f"per-table ranges {cfg['history']}")

    for pk in range(start_at, total + 1):
        rng = random.Random(f"{cfg['seed']}:history:{pk}")
        ctx = {"mode": "history", "epoch": epoch, "now": epoch}

        ref_row = _build_row(REF, pk, rng, ctx)
        op.upsert(table=REF["table"], data=_serialise(ref_row))

        child_ctx = dict(ctx, anchor=ref_row[REF["anchor_column"]])
        for child in CHILDREN:
            lo, hi = cfg["history"][child["table"]]
            for _ in range(rng.randint(lo, hi)):
                row_id = state["next_ids"][child["table"]]
                row = _build_row(child, row_id, rng, child_ctx, fk_value=pk)
                op.upsert(table=child["table"], data=_serialise(row))
                state["next_ids"][child["table"]] = row_id + 1

        state["history_cursor"] = pk
        if pk % HISTORY_CHECKPOINT_EVERY == 0:
            op.checkpoint(state)

    state["history_complete"] = True
    state["sync_count"] = 1
    state["last_tables_updated"] = [REF["table"]] + [c["table"] for c in CHILDREN]
    log.info("History load complete. Rows created per table: "
             + ", ".join(f"{t}={n - 1}" for t, n in state["next_ids"].items())
             + f", {REF['table']}={total}")
    op.checkpoint(state)


def incremental_load(cfg, state):
    sync_no = state["sync_count"] + 1
    rng = random.Random(f"{cfg['seed']}:sync:{sync_no}")
    now = _utc_now()
    ctx = {"mode": "incremental", "epoch": now, "now": now}

    how_many_tables = rng.choice([1, 2])
    chosen = rng.sample(CHILDREN, how_many_tables)
    total = state["reference_total"]
    summary = {}

    for child in chosen:
        count = rng.randint(cfg["incremental_min"], cfg["incremental_max"])
        for _ in range(count):
            row_id = state["next_ids"][child["table"]]
            owner = rng.randint(1, total)
            row = _build_row(child, row_id, rng, ctx, fk_value=owner)
            op.upsert(table=child["table"], data=_serialise(row))
            state["next_ids"][child["table"]] = row_id + 1
        summary[child["table"]] = count

    state["sync_count"] = sync_no
    state["last_tables_updated"] = list(summary)
    log.info(f"Sync #{sync_no}: appended rows to {summary}. "
             f"Untouched: {[c['table'] for c in CHILDREN if c['table'] not in summary] + [REF['table']]}")
    op.checkpoint(state)


def update(configuration, state):
    cfg = parse_config(configuration)
    if not state or "next_ids" not in state:
        state = _fresh_state(cfg)

    if not state["history_complete"]:
        historical_load(cfg, state)
    else:
        incremental_load(cfg, state)


connector = Connector(update=update, schema=schema)

