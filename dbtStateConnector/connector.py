"""
dbt state demo connector  (theme: retail)

Generated by the fivetran-dbt-state-demo skill.

What it does
------------
Builds a four-table schema: one reference table plus three behaviour tables that
reference it by primary key.

  sync 1 (history)   Creates N reference rows. Each reference row gets a random
                     number of rows (min..max inclusive, set per table) in every
                     behaviour table, all keyed back to the reference PK.
  sync 2..n          Picks ONE or TWO behaviour tables at random and appends new
                     rows to them. The reference table and the untouched
                     behaviour table(s) receive no data, so downstream dbt models
                     that depend only on those tables have nothing new to build.
                     That is what dbt state-aware selection exploits.

All sizing is read from configuration.json. Output is deterministic for a given
seed, so a demo can be replayed.
"""

